import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import {execFileSync} from 'node:child_process';
import {renderedHeadings} from './rendered-headings.mjs';
const source=fs.readFileSync('content/mpc/mpc-principle.mdx','utf8');
const aliases=[...source.matchAll(/<span id="([^"]+)" \/>/g)].map(m=>m[1]);
assert.equal(aliases.length,14);
assert.equal(new Set(aliases).size,aliases.length,'Duplicate compatibility aliases');
const headings=await renderedHeadings(source,'mpc/mpc-principle');
assert.equal(new Set([...headings.ids,...aliases]).size,headings.ids.length+aliases.length,'Alias collides with heading');
const m={};
new Function('exports',ts.transpileModule(fs.readFileSync('lib/mpc-principle.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(m);
const cases=[];
for(const x of [-6,-1,0,1,4,6])for(const r of [0,.25,1,4])for(const limit of [.25,1,2])cases.push({x,r,limit,result:m.mpcTwoStep(x,r,limit)});
assert.deepEqual(m.mpcTwoStep().u,[-1,-.25]);
for(const args of [[NaN,1,1],[4,-1,1],[4,1,0],[Infinity,1,1]])assert.throws(()=>m.mpcTwoStep(...args),RangeError);
fs.writeFileSync('.agent/semester-03/mpc-01/actual-ts.json',JSON.stringify(cases));
const out=execFileSync('python',['.agent/semester-03/mpc-01/reference.py'],{encoding:'utf8'});
fs.writeFileSync('.agent/semester-03/mpc-01/reconciliation.log',out);
console.log(out);

import fs from 'node:fs';
import {renderedHeadings} from '../../../scripts/rendered-headings.mjs';
const key='robot-learning/robot-data', dir='.agent/semester-03/rlearn-01/';
const headings=await renderedHeadings(fs.readFileSync('content/'+key+'.mdx','utf8'),key);
fs.writeFileSync(dir+'headings.json',JSON.stringify(headings,null,2)+'\n');
const p='content/catalog.ts';let catalog=fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n');
const start=catalog.indexOf('      {\n        "slug": "robot-data"');
const end=catalog.indexOf('      {\n        "slug": "imitation-learning"',start);
if(start<0||end<0)throw Error('catalog block absent');
const record={slug:'robot-data',title:'机器人数据',subsections:headings.h2.map(h=>({slug:h.id,title:h.text})),prereq:['machine-learning/learning-problem','math/probability-basics'],level:'grad',type:'learning',status:'draft'};
catalog=catalog.slice(0,start)+JSON.stringify(record,null,2).split('\n').map(l=>'      '+l).join('\n')+',\n'+catalog.slice(end);
fs.writeFileSync(p,catalog);
const cp='.agent/semester-03-checklist.md',pp='.agent/semester-03-plan.md';
let c=fs.readFileSync(cp,'utf8'),plan=fs.readFileSync(pp,'utf8');
const rows=c.split(/\r?\n/).filter(l=>/^\| [A-Z]+-\d+ \|/.test(l));
const before=rows.slice(0,rows.findIndex(l=>l.startsWith('| RLEARN-01 |')));
const skipped=before.filter(l=>l.split('|')[7].trim()!=='[x]').map(l=>l.split('|')[1].trim());
const exception='| RLEARN-01 | '+skipped.join(';')+' | 2026-10-24用户指定继续RLEARN-01，rank12；保留并行课程，只依赖已交付学习问题和概率基础，局部解释数据接口 | '+dir+'acceptance.md |';
const marker='<!-- S3-ORDER-EXCEPTIONS-END -->';
const old=plan.split(/\r?\n/).find(l=>l.startsWith('| RLEARN-01 |')&&l.includes('用户'));
plan=old?plan.replace(old,exception):plan.replace(marker,exception+'\n'+marker);
fs.writeFileSync(pp,plan);
c=c.replace(/^\| RLEARN-01 .*$/m,'| RLEARN-01 | [x] | [x] | [ ] | [ ] | [ ] | [ ] | docs/discuss-log/semester-03/18-robot-learning/01-robot-data.md;'+dir+'acceptance.md;rank12，独立副本与端口8202/9002 |');
fs.writeFileSync(cp,c);
console.log(JSON.stringify({key,h2:headings.h2.length,skipped:skipped.length,status:record.status}));

import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {extractNotebooks} from '../../../../scripts/lib-mdx.mjs';
import {renderedHeadings} from '../../../../scripts/rendered-headings.mjs';
const d='.agent/semester-03/polish/classic-01/';
const read=p=>readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const hash=s=>createHash('sha256').update(s.replace(/\r\n/g,'\n')).digest('hex');
const source=read('content/classic/system-modeling.mdx'),before=read(d+'source-before.mdx');
const code=s=>extractNotebooks(s).map(n=>({title:n.title,setup:n.setup.value,cells:n.cells.map(c=>c.value)}));
assert.deepEqual(code(source),code(before));assert.equal(code(source).length,7);
const h=await renderedHeadings(source,'classic/system-modeling'),old=await renderedHeadings(before,'classic/system-modeling');
assert.deepEqual(h.h2,old.h2);old.ids.forEach(id=>assert(h.ids.includes(id)));
const audit=json(d+'pyodide.json'),r=json(d+'reconciliation.json'),nb=json(d+'notebooks.json');
assert.equal(r.sourceHash,hash(source));assert(r.pass);
assert.equal(audit.lessons[0].sourceHash,hash(source));assert(audit.complete);
assert(audit.lessons[0].notebooks.length===7&&audit.lessons[0].notebooks.every(n=>n.status==='passed'&&n.cells.every(c=>c.status==='passed')));
assert.equal(nb.executionStatus,'EXECUTED');assert.equal(nb.totals.FAIL,0);assert.equal(nb.totals.SKIPPED,0);
assert.deepEqual(json('docs/deployment/python-expansion-pending.json'),json(d+'pending-before.json'));
const checklist=read('.agent/semester-03-checklist.md'),section=checklist.split('<!-- S3-POLISH-BEGIN -->')[1].split('<!-- S3-POLISH-END -->')[0];
const rows=section.split('\n').filter(l=>/^\| (?:MATH|CLASSIC|MODERN|NONLINEAR)-\d+ \|/.test(l));
assert.equal(rows.length,40);assert.equal(new Set(rows.map(l=>l.split('|')[1].trim())).size,40);
assert(rows.every(l=>l.split('|')[5].trim()==='[ ]'),'User has not reviewed any polish yet');
assert(rows.filter(l=>!l.includes('CLASSIC-01')).every(l=>!l.includes('[x]')),'Only pilot is authorized before user feedback');
const b=json(d+'browser.json');assert.deepEqual(b.h2,h.h2.map(v=>({id:v.id,text:v.text})));
assert.equal(b.katexErrors,0);assert.equal(new Set(b.ids).size,b.ids.length);old.ids.forEach(id=>assert(b.ids.includes(id)));
assert(b.targets.every(t=>t.exists));assert(b.images.every(i=>i.loaded));assert.equal(b.console.length,0);
assert(b.toolbars.length===2&&b.toolbars.every(t=>t.status==='运行完成'));
assert.equal(b.mobile.width,b.mobile.scrollWidth);assert.equal(b.mobile.viewport,360);
assert(b.initialAllHiddenNotices&&b.prereqClean&&b.emptyPrereqHidden&&b.optionalOpened);
assert(read('.agent/semester-03/language-memory.md').includes(hash(source)));
assert(read('.agent/skills/wiki-discussion/personas.md').includes('| **具名合计** | **24**'));
const record={pass:true,sourceHash:hash(source),codeUnchanged:true,notebooks:7,cells:7,h2:13,oldIds:old.ids.length,domIds:b.ids.length,polishQueue:40,userAccepted:false,componentCases:r.cases.length,maxStateError:r.maxError};
writeFileSync(d+'preservation.json',JSON.stringify({...record,h2:h.h2,ids:h.ids},null,2)+'\n');
writeFileSync(d+'validation.json',JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify(record));

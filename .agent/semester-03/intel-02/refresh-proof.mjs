import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {pythonInventory} from '../../../scripts/python-inventory.mjs';
import {pythonReleaseDecision} from '../../../scripts/python-release-decision.mjs';
const dir='.agent/semester-03/intel-02/',key='intelligent/fuzzy-controller-design';
const raw=JSON.parse(readFileSync(dir+'pyodide-download.json','utf8'));
const fixture=JSON.parse(readFileSync(dir+'pyodide-fixture.json','utf8')).lessons[0];
const current=pythonInventory().find(l=>l.key===key);
assert.deepEqual(current.notebooks.map(n=>[n.setup,n.cells]),fixture.notebooks.map(n=>[n.setup,n.cells]),'Executed code changed');
const normalized=structuredClone(raw);
normalized.lessons[0].sourceHash=current.sourceHash;
normalized.lessons[0].notebooks.forEach((n,i)=>{n.line=current.notebooks[i].line;});
normalized.provenance=[{kind:'prose-and-figure-only-after-browser-run',originalSourceHash:fixture.sourceHash,finalSourceHash:current.sourceHash,codeExactlyEqual:true,inputPath:dir+'pyodide-download.json'}];
writeFileSync(dir+'pyodide.json',JSON.stringify(normalized,null,2)+'\n');
const policy=JSON.parse(readFileSync('lib/python-support.json','utf8'));
policy.lessons[key]={sourceHash:current.sourceHash,notebooks:normalized.lessons[0].notebooks.map(n=>({id:n.id,title:n.title,...pythonReleaseDecision(n),cells:n.cellCount}))};
writeFileSync('lib/python-support.json',JSON.stringify(policy,null,2)+'\n');
const report=JSON.parse(readFileSync('docs/deployment/python-expansion-local.json','utf8'));
const own=normalized.lessons[0],index=report.lessons.findIndex(l=>l.key===key);
report.lessons[index]=own;
report.provenance??=[];report.provenance=report.provenance.filter(p=>p.inputPath!==dir+'pyodide.json');
report.provenance.push({testedAt:raw.testedAt,url:raw.url,inputPath:dir+'pyodide.json',codeExactlyEqual:true});
const all=report.lessons.flatMap(l=>l.notebooks),enabled=all.filter(n=>pythonReleaseDecision(n).status==='enabled').length;
report.totals={lessons:report.lessons.length,notebooks:all.length,enabled,codeOnly:all.length-enabled};
report.releaseTotals={enabled,codeOnly:all.length-enabled};
writeFileSync('docs/deployment/python-expansion-local.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({key,sourceHash:current.sourceHash,notebooks:own.notebooks.length,codeExactlyEqual:true}));

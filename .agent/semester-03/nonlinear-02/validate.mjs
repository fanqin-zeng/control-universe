import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {extractNotebooks} from '../../../scripts/lib-mdx.mjs';
import {renderedHeadings} from '../../../scripts/rendered-headings.mjs';
const root='.agent/semester-03/nonlinear-02/';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const hash=p=>createHash('sha256').update(readFileSync(p,'utf8').replace(/\r\n/g,'\n')).digest('hex');
const source='content/nonlinear/phase-plane.mdx',r=read(root+'reconciliation.json'),a=read(root+'pyodide.json'),b=read(root+'browser.json'),n=read(root+'notebooks.json');
assert(r.pass&&a.complete&&a.lessons.length===1);
assert.equal(r.hashes.source,hash(source));
for(const name of ['phase-plane','trace-det'])assert.equal(r.hashes[name],hash(`components/wiki/${name}-explorer.tsx`));
assert.equal(a.lessons[0].sourceHash,hash(source));
assert.equal(a.lessons[0].notebooks.length,14);
assert(a.lessons[0].notebooks.every(nb=>nb.status==='passed'&&nb.cells.every(c=>c.status==='passed')));
assert.equal(n.executionStatus,'EXECUTED');assert.equal(n.totals.FAIL,0);assert.equal(n.totals.SKIPPED,0);
assert.equal(n.lessons[0].notebooks,14);assert.equal(n.lessons[0].cells.length,27);
assert.equal(r.notebooks.length,14);assert.equal(r.notebooks.reduce((s,nb)=>s+nb.cells.length,0),27);
assert.deepEqual(read('docs/deployment/python-expansion-pending.json'),read(root+'baseline-python-pending.json'));
const h=await renderedHeadings(readFileSync(source,'utf8'),'nonlinear/phase-plane');
assert.deepEqual(b.static.h2,h.h2.map(x=>({id:x.id,text:x.text})));
assert.equal(b.static.errors,0);assert.equal(new Set(b.static.ids).size,b.static.ids.length);
read(root+'baseline-source.json').ids.forEach(id=>assert(b.static.ids.includes(id),id));
assert(b.static.targets.every(t=>t.exists));assert(b.static.images.every(i=>i.loaded));
for(const size of [360,375]){const v=b['mobileFinal'+size];assert.equal(v.width,size);assert.equal(v.scrollWidth,size);}
assert(b.productionNotebooks.length===3&&b.productionNotebooks.every(nb=>nb.complete&&!nb.error));
assert.equal(b.console.length,0);
const notebooks=extractNotebooks(readFileSync(source,'utf8'));
writeFileSync(root+'delivery-validation.json',JSON.stringify({pass:true,sourceHash:hash(source),components:r.hashes,notebooks:14,cells:27,codeHash:createHash('sha256').update(JSON.stringify(notebooks.map(nb=>({setup:nb.setup.value,cells:nb.cells.map(c=>c.value)})))).digest('hex'),oldIds:25,domIds:b.static.ids.length,h2:15,pythonPending:25,phaseCases:r.component.phaseCases,traceCases:r.component.traceCases,maxStateError:r.component.maxStateError,thresholdError:r.component.thresholdError,mobileWidths:[360,375],productionToolbars:3},null,2)+'\n');
console.log('PASS NONLINEAR-02 final source/components, native/Pyodide, DOM/anchors, mobile and pending invariants');

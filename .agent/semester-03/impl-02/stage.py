"""Stage the lesson and HEAD+lesson shared files, preserving parallel work."""
from pathlib import Path
import subprocess,json,os,sys
root=Path(__file__).resolve().parents[3];snap=root.parent/'control-universe-rank1-impl02-validation'
env=os.environ.copy()
if '--isolated' in sys.argv:
    env['GIT_INDEX_FILE']=str(snap/'rank1-impl02.index')
def git(*args,**kwargs):return subprocess.check_output(['git',*args],cwd=root,env=env,**kwargs)
meta=json.loads((root/'.agent/semester-03/impl-02/staging-base.json').read_text(encoding='utf-8'))
assert git('rev-parse','HEAD',text=True).strip()==meta['base'],'HEAD advanced: refresh metadata before staging'
if '--isolated' in sys.argv:
    git('read-tree','HEAD')
assert not git('diff','--cached','--name-only').strip(),'Another session is staging; wait without touching its index'
evidence=root/'.agent/semester-03/impl-02'
assert 'PASS 21 · WARN 2 · FAIL 0' in (evidence/'scoped-check.log').read_text(encoding='utf-8'),'Wait for successful independent catalog check'
assert 'PASS fix-log index/details' in (evidence/'fix-check-scoped.log').read_text(encoding='utf-8')
assert not json.loads((evidence/'scoped-semester.json').read_text(encoding='utf-8'))['errors']
for rel in ['lib/python-support.json','docs/deployment/python-expansion-local.json']:
    old=json.loads(git('show',meta['base']+':'+rel));new=json.loads((snap/rel).read_text(encoding='utf-8'))
    oldrows=old['lessons'] if isinstance(old['lessons'],dict) else {r['key']:r for r in old['lessons']}
    newrows=new['lessons'] if isinstance(new['lessons'],dict) else {r['key']:r for r in new['lessons']}
    assert set(oldrows)==set(newrows)
    assert all(oldrows[k]==newrows[k] for k in oldrows if k!='implementation/digital-pid'),rel
own=['content/implementation/digital-pid.mdx','lib/digital-pid.ts','components/wiki/digital-pid-explorer.tsx','public/diagrams/implementation/pid-cascade.svg','scripts/verify-impl02.mjs','docs/discuss-log/semester-03/07-implementation/02-digital-pid.md','.agent/fix-logs/2026-10-24-074.md']
own += [p.relative_to(root).as_posix() for p in (root/'.agent/semester-03/impl-02').rglob('*') if p.is_file() and '__pycache__' not in p.parts]
for p in own:assert (root/p).exists(),p
subprocess.run(['git','add','--',*own],cwd=root,env=env,check=True)
for rel in meta['shared']:
    # The isolated metadata was regenerated by the repository's own tools.
    oid=git('hash-object','-w','--path='+rel,'--stdin',input=(snap/rel).read_bytes()).decode().strip()
    subprocess.run(['git','update-index','--add','--cacheinfo','100644,'+oid+','+rel],cwd=root,env=env,check=True)
paths=git('diff','--cached','--name-only',text=True,encoding='utf-8').splitlines()
assert set(paths)<=set(own+meta['shared']),paths
assert git('rev-parse','HEAD',text=True).strip()==meta['base'],'HEAD changed while staging: inspect before committing'
subprocess.run(['git','diff','--cached','--check','--','.',':(glob,exclude)**/*.log',':(exclude).agent/semester-03/impl-02/source-before.mdx'],cwd=root,env=env,check=True)
print(json.dumps({'base':meta['base'],'count':len(paths),'otherPythonRecordsUnchanged':True,'isolated':'--isolated' in sys.argv},ensure_ascii=False))
